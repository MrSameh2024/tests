/* Smart Students Hub · item-level bilingual explanations ("Why? · لماذا؟")
   After the student checks the test, every multiple-choice, true/false and word-formation item gets
   a short explanation of the correct answer in English and Arabic, and — when the student chose a
   wrong option — why that option does not fit. Opens automatically for wrong answers.
   Data: window.SSH_FB_ITEMS (feedback/<page>.js, generated by src/feedback/build_g11_feedback.py).
   Skill rules, examples, common mistakes and resources are shown by ssh-pathways.js; this file adds the item level.
   Nothing is stored or sent. */
(function () {
  'use strict';
  var F = window.SSH_FB_ITEMS;
  if (!F || window.__sshFb) return;
  window.__sshFb = true;
  var t = String(parseInt(new URLSearchParams(location.search).get('t'), 10) || 1);
  var items = F.tests[t]; if (!items) return;
  var esc = function (s) { return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); };
  var css = document.createElement('style');
  css.textContent = '.sshx{margin:6px 0 2px;border:1px solid #d6e0ee;border-radius:10px;background:#fbfcfe;font-size:.9rem}' +
    '.sshx summary{cursor:pointer;padding:6px 10px;font-weight:700;color:#26357a;list-style:revert}' +
    '.sshx .b{padding:2px 12px 10px}.sshx p{margin:6px 0}.sshx .ar{direction:rtl;text-align:right;display:block;font-family:Tahoma,"Segoe UI",Arial,sans-serif;color:#33415c}' +
    '.sshx .no{border-left:3px solid #b3261e;padding-left:8px}.sshx .k{background:#e6f4ea;border-radius:6px;padding:0 6px;font-weight:700}' +
    '.sshx ul{margin:4px 0 0;padding-left:18px}.sshx li{margin:3px 0}';
  document.head.appendChild(css);

  function chosen(id) {
    var m = /^(a|v|g)(\d)$/.exec(id), tf = /^tf(\d)$/.exec(id), el;
    if (m) { el = document.querySelector('input[name="' + id + '"]:checked'); if (!el) return null; var lab = el.closest('label'); return lab ? lab.textContent.replace(/^\s*[a-d]\)\s*/, '').trim() : el.value; }
    if (tf) { el = document.querySelector('input[name="' + id + '"]:checked'); return el ? el.value : null; }
    el = document.getElementById(id); return el ? el.value.trim() : null;
  }
  function render() {
    Object.keys(items).forEach(function (id) {
      var box = document.getElementById(id + 'fb'); if (!box || box.querySelector('.sshx')) return;
      var e = items[id], wrong = !!box.querySelector('.fb.no, .fb.review'), pick = chosen(id);
      var h = '<details class="sshx"' + (wrong ? ' open' : '') + '><summary>Why? · لماذا؟</summary><div class="b">';
      h += '<p>Answer · الإجابة: <span class="k">' + esc(e.k) + '</span></p>';
      h += '<p>' + esc(e.en) + '<span class="ar" lang="ar">' + esc(e.ar) + '</span></p>';
      var mine = null;
      if (wrong && pick) e.not.forEach(function (n) { if (n[0].toLowerCase() === pick.toLowerCase()) mine = n; });
      if (mine) h += '<p class="no">Your answer <b>' + esc(mine[0]) + '</b>: ' + esc(mine[1]) + '<span class="ar" lang="ar">إجابتك <b dir="ltr">' + esc(mine[0]) + '</b>: ' + esc(mine[2]) + '</span></p>';
      var others = e.not.filter(function (n) { return n !== mine; });
      if (others.length) h += '<details><summary style="font-weight:600">Why not the other options? · لماذا لا تصلح الخيارات الأخرى؟</summary><ul>' + others.map(function (n) {
        return '<li><b>' + esc(n[0]) + '</b> — ' + esc(n[1]) + '<span class="ar" lang="ar">' + esc(n[2]) + '</span></li>'; }).join('') + '</ul></details>';
      box.insertAdjacentHTML('beforeend', h + '</div></details>');
    });
  }
  document.addEventListener('click', function (ev) { if (ev.target && ev.target.id === 'yesBtn') setTimeout(render, 0); });
  window.SSH_FB = { render: render };
})();
